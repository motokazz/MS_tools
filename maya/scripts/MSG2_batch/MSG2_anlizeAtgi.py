def SAVE(ROW=[],FILE_PATH=''):
	f=open(FILE_PATH,'w')#'r'読み込み：'w'書き込み：'a'追記：'+'読み書き両方' 't'テキストモード：'b'バイナリーモード
	for each in ROW:
		f.write(each+'\n')
	f.close()

def SAVEDICT(ROW={},FILE_PATH=''):
	f=open(FILE_PATH,'w')#'r'読み込み：'w'書き込み：'a'追記：'+'読み書き両方' 't'テキストモード：'b'バイナリーモード
	for each in ROW.keys():
		f.write(each.replace('\n','')+','+','.join(ROW[each])+'\n')
	f.close()

def LOAD(FILE_PATH):
	f=open(FILE_PATH)
	DATA=[]
	for ROW in f:
		DATA.append(ROW)
	f.close()
	return DATA

#別のATGIで配置されているATGIを調べる
def list_atgiInAtgi(ATGI_PATHS=[]):

	RESULT={}

	#プログレスバー
	MS_Progress()
	cmds.progressBar('MS_progress',edit=True,beginProgress=True,isInterruptable=True,maxValue=len(ATGI_PATHS))

	for ATGI_PATH in ATGI_PATHS:
		ATGI_NAME=ATGI_PATH.split('/')[-1].split('\\')[-1].split('.')[0]
		DATA=LOAD(ATGI_PATH)
		for EACHDATA in DATA:
			if u'<attribute name="atgiFilename" type="string">' in EACHDATA:
				EACHDATA=EACHDATA.replace('<attribute name="atgiFilename" type="string">','')
				EACHDATA=EACHDATA.replace('</attribute>','')
				EACHDATA=EACHDATA.replace('\n','')
				EACHDATA=EACHDATA.replace(' ','')
				EACHDATA=EACHDATA.split('/')[-1].split('\\')[-1].split('.')[0]

				if EACHDATA in RESULT.keys():
					if not ATGI_NAME in RESULT[EACHDATA]:
						RESULT[EACHDATA].append(ATGI_NAME)
					else:
						continue
				else:
					RESULT.setdefault(EACHDATA,[ATGI_NAME])

		cmds.progressBar('MS_progress',edit=True,s=1)#プログレス

	cmds.deleteUI('MS_ProgressWindow')#プログレス
	return RESULT

def listUnuzedAtgi(ATGI_NAMES=[]):
	LIST_ATGIINATGI=MS_CSVImportDict.indexColumn(EXPORT_PATH)
	RESULT=[]
	#プログレスバー
	MS_Progress()
	cmds.progressBar('MS_progress',edit=True,beginProgress=True,isInterruptable=True,maxValue=len(ATGI_NAMES))

	for ATGI_NAME in ATGI_NAMES:
		CHECK=True
		ATGI_NAME=ATGI_NAME.split('/')[-1].split('\\')[-1].split('.')[0]
		if '_brk_' in ATGI_NAME:
			CHECK=False
		else:
			for AINA in LIST_ATGIINATGI.keys():
				if ATGI_NAME == AINA:
					CHECK=False

		if CHECK:
			EX='X'
			if os.path.exists('D:/Projects/Gravite2/assets/bg/model/'+ATGI_NAME+'.atgi'):
				EX='O'
			RESULT.append(ATGI_NAME+','+EX)

		cmds.progressBar('MS_progress',edit=True,s=1)#プログレス
	cmds.deleteUI('MS_ProgressWindow')#プログレス
	return RESULT


